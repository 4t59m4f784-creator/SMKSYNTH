"""Extract pinned JIANT vowel-only render/glide; no WORDS, dictionaries or UI.
Reference e924445ae0e7c64636f15bd0758418ee312ce7ee is retained under tests/reference/jiant.
Only symbol names, defined signed arithmetic and exact coefficient caching change.
"""
import math,re
from pathlib import Path
root=Path(__file__).resolve().parents[1]
def write_generated(path, text):
 if not path.exists() or path.read_text()!=text:path.write_text(text)
def arr(name,typ,vals):
 return 'static const '+typ+' '+name+'['+str(len(vals))+']={\n'+',\n'.join(','.join(map(str,vals[i:i+8])) for i in range(0,len(vals),8))+'\n};\n'
ms=[10000**(v/127) for v in range(128)]
s='/* SPDX-License-Identifier: GPL-3.0-only\n * Generated by tools/gen_jiant_voice.py from the pinned JIANT formulas. */\n#pragma once\n'
s+=arr('JV_TIME_MS_X10','uint32_t',[round(m*10) for m in ms])
s+=arr('JV_ENV_LIN','uint32_t',[max(1,int((1<<24)*32/(m*44100/1000))) for m in ms])
s+=arr('JV_ENV_EXP','uint16_t',[max(1,min(65535,int(65536*(1-math.exp(-32/(m/1000/4.6*44100)))))) for m in ms])
s+=arr('JV_PITCH_OCT','uint32_t',[min(int(440*2**((p/16-69)/12)/44100*2**32),0x7fffffff) for p in range(1856,2048)])
s+='static uint32_t jv_pitch_inc(uint32_t p){uint32_t i=p+64u,o=(i*21846u)>>22;return JV_PITCH_OCT[i-o*192u]>>(10u-o);}\n'
write_generated(root/'firmware/gen/obv_jiant_tables.h',s)
src=(root/'tests/reference/jiant/eng_formant.c').read_text()
glide=src[src.index('static int32_t glide_sung('):src.index('typedef struct { int32_t a, b, c; } fres_t;')]
render=src[src.index('static void formant_render('):src.index('static const preset_t FORMANT_PRESETS')]
start=render.index('    if (p[P_VLANG])');end=render.index('    if (v->pitch_cur',start);render=render[:start]+render[end:]
render=render.replace('track_t *t, voice_t *v','jv_state_t *st, jv_track_t *t, jv_voice_t *v')
for j in range(1,5):render=render.replace('fres_coef(&r'+str(j)+',','jv_cached(st,'+str(j-1)+', &r'+str(j)+',')
s=glide+render
for a,b in [('voice_t','jv_voice_t'),('vmod_t','jv_mod_t'),('glide_sung','jv_glide_sung'),('fmt_sung','jv_sung'),('formant_render','jv_render32'),('pitch_inc','jv_pitch_inc'),('sine_i','fmt_sine'),('blep','fmt_blep'),('noise32','jv_noise32'),('formant_nz','jv_noise'),('ENV_LIN','JV_ENV_LIN'),('FMT_TALK_MASK','JV_TALK_MASK'),('voice_amp','jv_amp'),('soft_knee','jv_knee'),('clamp','clampi')]:s=re.sub(r'\b'+a+r'\b',b,s)
# Avoid negative signed left shifts, preserving two's complement values.
s=s.replace('v->pitch_cur << 8','v->pitch_cur * 256').replace('(v->gfrom << 8)','(v->gfrom * 256)')
s=s.replace('((v->pitch_cur - v->gfrom) << 8)','((v->pitch_cur - v->gfrom) * 256)').replace(')) << 4) / d', ')) * 16) / d')
s=s.replace('(x << 6)','(x * 64)').replace('jv_amp(s, m, i) << 1','jv_amp(s, m, i) * 2')
write_generated(root/'firmware/gen/obv_jiant_kernel.h','/* SPDX-License-Identifier: GPL-3.0-only\n * Copyright (C) 2026 Leo Kuroshita (@kurogedelic), Hügelton Instruments\n * Portions Copyright (C) 2026 Juan Ignacio Antonucci (Juan Jiant)\n * Generated vowel-only kernel; see tools/gen_jiant_voice.py. */\n'+s)
